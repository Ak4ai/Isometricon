# Where the old head put it: the bottom of the head and the plane of the face.
HEAD_BOTTOM, FACE_FRONT = 1.492, 0.133


def rows_for(head_rows: np.ndarray):
    """(vertex rows of 11 floats, triangles) of the nose on a head given by its vertex rows: at the
    same height above the bottom of the head as on the old one, and on the plane of this face."""
    head = np.asarray(head_rows, dtype=np.float64).reshape(-1, 11)[:, :3]
    lift = head[:, 1].min() - HEAD_BOTTOM
    low, high = ROWS[:, 1].min() + lift, ROWS[:, 1].max() + lift
    face = head[(np.abs(head[:, 0]) < 0.05) & (head[:, 1] > low - 0.03) & (head[:, 1] < high + 0.03)]
    front = face[:, 2].max() if len(face) else head[:, 2].max()
    rows = np.ones((len(ROWS), 11), dtype=np.float32)  # colour (the last three) stays white
    rows[:, :8] = ROWS
    rows[:, 1] += lift
    rows[:, 2] += front - FACE_FRONT
    return rows, TRIANGLES.copy()
